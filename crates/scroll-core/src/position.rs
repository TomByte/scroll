//! Sibling order as fractional index strings: a new position can always be made between two others,
//! so a move or insert writes one field and never renumbers siblings.

use loro::FractionalIndex;
use rusqlite::types::{FromSql, FromSqlError, FromSqlResult, ToSql, ToSqlOutput, ValueRef};
use serde::{Deserialize, Serialize};

/// Uppercase hex of a fractional index. Hex keeps byte order under plain string comparison,
/// so SQL `ORDER BY position` sorts correctly. Two clients inserting at the same place
/// concurrently can produce equal positions; readers break ties by record id.
#[derive(Debug, Clone, PartialEq, Eq, PartialOrd, Ord, Hash, Serialize, Deserialize)]
pub struct Position(String);

#[derive(Debug, Clone, PartialEq, Eq, thiserror::Error)]
pub enum PositionError {
    #[error("position {0:?} is not a well-formed fractional index")]
    Malformed(String),
    #[error("no position fits between {before:?} and {after:?}: they are equal or out of order")]
    NoRoomBetween { before: String, after: String },
}

/// Every index generated by the algorithm ends in this byte; without it, generating a neighbour can fail.
const TERMINATOR_HEX: &str = "80";

impl Position {
    /// A position after `before` and before `after`; `None` means that side is open.
    pub fn between(
        before: Option<&Position>,
        after: Option<&Position>,
    ) -> Result<Position, PositionError> {
        let before_index = before.map(Position::to_fractional_index).transpose()?;
        let after_index = after.map(Position::to_fractional_index).transpose()?;
        let index =
            FractionalIndex::new(before_index.as_ref(), after_index.as_ref()).ok_or_else(|| {
                PositionError::NoRoomBetween {
                    before: before.map_or_else(String::new, |position| position.0.clone()),
                    after: after.map_or_else(String::new, |position| position.0.clone()),
                }
            })?;
        Ok(Position(index.to_string()))
    }

    /// `count` positions in order, all after `before` and before `after`, spread so that their
    /// length grows with the logarithm of `count` (appending one at a time grows it linearly).
    #[cfg(any(test, feature = "fixture"))]
    pub(crate) fn many_between(
        before: Option<&Position>,
        after: Option<&Position>,
        count: usize,
    ) -> Result<Vec<Position>, PositionError> {
        let before_index = before.map(Position::to_fractional_index).transpose()?;
        let after_index = after.map(Position::to_fractional_index).transpose()?;
        let indexes =
            FractionalIndex::generate_n_evenly(before_index.as_ref(), after_index.as_ref(), count)
                .ok_or_else(|| PositionError::NoRoomBetween {
                    before: before.map_or_else(String::new, |position| position.0.clone()),
                    after: after.map_or_else(String::new, |position| position.0.clone()),
                })?;
        Ok(indexes
            .into_iter()
            .map(|index| Position(index.to_string()))
            .collect())
    }

    /// Accepts a position received from elsewhere, such as the wire or the database.
    pub fn parse(text: &str) -> Result<Position, PositionError> {
        let position = Position(text.to_owned());
        position.to_fractional_index()?;
        Ok(position)
    }

    pub fn as_str(&self) -> &str {
        &self.0
    }

    pub fn is_well_formed(&self) -> bool {
        let text = &self.0;
        !text.is_empty()
            && text.len().is_multiple_of(2)
            && text.ends_with(TERMINATOR_HEX)
            && text
                .bytes()
                .all(|byte| byte.is_ascii_digit() || (b'A'..=b'F').contains(&byte))
    }

    fn to_fractional_index(&self) -> Result<FractionalIndex, PositionError> {
        // `from_hex_string` panics on bad input, so the format is checked first.
        if !self.is_well_formed() {
            return Err(PositionError::Malformed(self.0.clone()));
        }
        Ok(FractionalIndex::from_hex_string(&self.0))
    }
}

impl ToSql for Position {
    fn to_sql(&self) -> rusqlite::Result<ToSqlOutput<'_>> {
        self.0.to_sql()
    }
}

impl FromSql for Position {
    fn column_result(value: ValueRef<'_>) -> FromSqlResult<Self> {
        Position::parse(value.as_str()?).map_err(|error| FromSqlError::Other(Box::new(error)))
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn positions_sort_between_their_neighbours() {
        let first = Position::between(None, None).unwrap();
        let last = Position::between(Some(&first), None).unwrap();
        let before_first = Position::between(None, Some(&first)).unwrap();
        let middle = Position::between(Some(&first), Some(&last)).unwrap();

        assert!(before_first < first);
        assert!(first < middle);
        assert!(middle < last);
        assert!(
            [&before_first, &first, &middle, &last]
                .iter()
                .all(|position| position.is_well_formed())
        );
    }

    #[test]
    fn repeated_inserts_at_the_same_gap_stay_ordered() {
        let low = Position::between(None, None).unwrap();
        let mut high = Position::between(Some(&low), None).unwrap();
        for _ in 0..200 {
            let next = Position::between(Some(&low), Some(&high)).unwrap();
            assert!(low < next && next < high);
            high = next;
        }
    }

    #[test]
    fn many_positions_are_ordered_short_and_inside_their_bounds() {
        let low = Position::between(None, None).unwrap();
        let high = Position::between(Some(&low), None).unwrap();
        let positions = Position::many_between(Some(&low), Some(&high), 100_000).unwrap();
        assert_eq!(positions.len(), 100_000);
        assert!(positions.windows(2).all(|pair| pair[0] < pair[1]));
        assert!(low < positions[0] && positions[99_999] < high);
        assert!(positions.iter().all(Position::is_well_formed));
        assert!(
            positions
                .iter()
                .all(|position| position.as_str().len() <= 40)
        );
        assert!(Position::many_between(Some(&high), Some(&low), 2).is_err());
        assert_eq!(Position::many_between(None, None, 3).unwrap().len(), 3);
    }

    #[test]
    fn equal_neighbours_have_no_room_between() {
        let position = Position::between(None, None).unwrap();
        assert!(matches!(
            Position::between(Some(&position), Some(&position)),
            Err(PositionError::NoRoomBetween { .. })
        ));
    }

    #[test]
    fn malformed_positions_are_rejected_without_panicking() {
        for text in ["", "8", "zz80", "0a80", "7F"] {
            assert!(
                Position::parse(text).is_err(),
                "{text:?} should be rejected"
            );
        }
        assert!(Position::parse("7F80").is_ok());
    }
}
