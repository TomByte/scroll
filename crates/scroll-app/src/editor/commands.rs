/// The kinds a block can be turned into, as the slash menu lists them.
fn block_kinds(_: &Target, _: &App) -> Vec<Choice> {
    SLASH_COMMANDS
        .iter()
        .filter_map(|command| match command.action {
            SlashAction::TurnInto(kind) => Some(Choice {
                label: command.label.into(),
                emoji: None,
                value: ChoiceValue::BlockKind(kind),
            }),
            SlashAction::CreateDatabase => None,
        })
        .collect()
}

