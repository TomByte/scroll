#!/usr/bin/env python3
"""Builds assets/emoji/emoji.tsv, the emoji picker's table, from Unicode's emoji-test.txt and
the English search keywords of Unicode CLDR.

Usage: python3 -I tools/emoji_table.py path/to/emoji-test.txt path/to/cldr > assets/emoji/emoji.tsv

emoji-test.txt is part of Unicode Technical Standard #51 (https://www.unicode.org/Public/emoji/).
`path/to/cldr` is a checkout or release of https://github.com/unicode-org/cldr (the table was last
built from tag release-49, CLDR 49); only common/annotations/en.xml,
common/annotationsDerived/en.xml and common/dtd/ldml.dtd (for the version) are read. Both sources
are distributed under the Unicode License v3 (https://www.unicode.org/license.txt), which permits
redistribution with the copyright notice, kept at the top of the generated file.

Only fully-qualified emoji without a skin-tone modifier are listed: the picker shows each emoji
once. Columns: emoji, name, group, subgroup, keywords. The subgroup (for example
"face-smiling") is searched as a weaker keyword. Keywords are CLDR's, split into lowercase words,
deduplicated, without the words already in the name, and joined by spaces.
"""
import re
import sys
import xml.etree.ElementTree as ElementTree
from pathlib import Path

SKIN_TONES = {0x1F3FB, 0x1F3FC, 0x1F3FD, 0x1F3FE, 0x1F3FF}
# CLDR writes its code points without the emoji presentation selector.
PRESENTATION_SELECTOR = "️"
# Matches how the picker splits names and queries into words.
WORD_SEPARATORS = re.compile(r"[\s\-:,]+")


def words(text):
    return [word for word in WORD_SEPARATORS.split(text.lower()) if word]


def read_emoji_test(path):
    group = subgroup = ""
    header = []
    rows = []
    with open(path, encoding="utf-8") as source:
        for line in source:
            line = line.rstrip("\n")
            if line.startswith("# group:"):
                group = line.split(":", 1)[1].strip()
            elif line.startswith("# subgroup:"):
                subgroup = line.split(":", 1)[1].strip()
            elif line.startswith(("# Date:", "# ©", "# Version:")):
                header.append(line)
            elif line and not line.startswith("#"):
                codes, rest = line.split(";", 1)
                status, comment = rest.split("#", 1)
                if status.strip() != "fully-qualified" or group == "Component":
                    continue
                points = [int(code, 16) for code in codes.split()]
                if SKIN_TONES & set(points):
                    continue
                # comment: " 😀 E1.0 grinning face"
                parts = comment.strip().split(" ", 2)
                rows.append((parts[0], parts[2], group, subgroup))
    return header, rows


def read_cldr_keywords(cldr):
    """Maps each emoji (without presentation selectors) to its CLDR keywords, in CLDR's order."""
    keywords = {}
    for name in ("annotations", "annotationsDerived"):
        tree = ElementTree.parse(Path(cldr, "common", name, "en.xml"))
        for annotation in tree.iter("annotation"):
            if annotation.get("type") == "tts" or not annotation.text:
                continue
            listed = keywords.setdefault(annotation.get("cp"), [])
            listed.extend(keyword.strip() for keyword in annotation.text.split("|"))
    return keywords


def find_in_cldr(cldr, relative_path, pattern):
    text = Path(cldr, "common", relative_path).read_text(encoding="utf-8")
    match = re.search(pattern, text)
    if not match:
        sys.exit(f"No match for {pattern} in common/{relative_path}")
    return match.group(1)


def keyword_column(name, cldr_keywords):
    name_words = set(words(name))
    unique = []
    for keyword in cldr_keywords:
        for word in words(keyword):
            if word not in name_words and word not in unique:
                unique.append(word)
    return " ".join(unique)


def main(emoji_test, cldr):
    header, rows = read_emoji_test(emoji_test)
    keywords = read_cldr_keywords(cldr)
    print("# Generated by tools/emoji_table.py from Unicode emoji-test.txt. Unicode License v3.")
    for line in header:
        print(line)
    version = find_in_cldr(cldr, "dtd/ldml.dtd", r'cldrVersion CDATA #FIXED "([^"]+)"')
    copyright = find_in_cldr(cldr, "annotations/en.xml", r"(Copyright © [^\n]*)")
    print(
        f"# Keywords: Unicode CLDR {version}, common/annotations/en.xml and "
        "common/annotationsDerived/en.xml. Unicode License v3."
    )
    print(f"# {copyright}")
    for emoji, name, group, subgroup in rows:
        cldr_keywords = keywords.get(emoji.replace(PRESENTATION_SELECTOR, ""), [])
        print("\t".join((emoji, name, group, subgroup, keyword_column(name, cldr_keywords))))


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
